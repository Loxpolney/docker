# Commit commands
git add .                            # Добавить индексацию
git commit -m                        # Сделать коммит
git push                             # Отправить изменения в удалённый репозиторий 
git pull                             # Слить изменения из удалённого репозитория
# Branches commands
git branch -m old-branch new-branch  # Создать новую ветку из той, в которой назвёте
git switch                           # Сменить ветку